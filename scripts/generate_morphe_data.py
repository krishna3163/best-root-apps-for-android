    target_apps = []
    for pkg in b.get("targetApps", []):
        app_info = store_raw.get(pkg)
        app_name = app_info.get("name") if app_info else pkg
        if app_name and app_name not in target_apps:
            target_apps.append(app_name)
    sample_patches = [p.get("name", "") for p in b.get("patches", [])[:5] if p.get("name")]

