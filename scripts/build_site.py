"""Build a searchable catalog website from README app tables and Morphe releases."""

from __future__ import annotations

import html
import json
import re
from pathlib import Path

from readme import README, read_catalog

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "site"
MORPHE_RELEASES_PATH = ROOT / "data" / "morphe-releases.json"


def build() -> None:
    content, entries = read_catalog()
    headings = list(re.finditer(r"^### (.+)$", content, re.MULTILINE))
    cursor = 0
    current_category = "Root Apps"
    categorized = []
    for entry in entries:
        position = content.find(entry["name"], cursor)
        while headings and headings[0].start() < position:
            current_category = headings.pop(0).group(1).replace("**", "")
        cursor = position + len(entry["name"])
        categorized.append((current_category, entry))

    cards = []
    for category, entry in categorized:
        cards.append(
            f'<article class="app" data-category="{html.escape(category)}" data-tags="catalog">'
            f'<h2><a href="{html.escape(entry["url"])}">{html.escape(entry["name"])}</a></h2>'
            f'<p>{entry["description"]}</p>'
            f'<small>{html.escape(category)} · {html.escape(entry["license"])}</small>'
            f'<a class="source" href="{html.escape(entry["url"])}">Open source</a>'
            "</article>"
        )

    # Load Morphe releases if present
    morphe_count = 0
    if MORPHE_RELEASES_PATH.exists():
        try:
            with open(MORPHE_RELEASES_PATH, "r", encoding="utf-8") as f:
                morphe_releases = json.load(f)
            for slug, item in sorted(morphe_releases.items()):
                morphe_count += 1
                name = item.get("name", slug)
                pkg = item.get("package_name", "")
                version = item.get("version", "")
                build_type = item.get("build_type", "autobuild")
                channel = item.get("channel", "stable")
                tag = item.get("release_tag", "")
                sha = item.get("sha256", "")[:12]
                patches = item.get("patches", [])
                patch_summary = ", ".join(patches[:3])
                if len(patches) > 3:
                    patch_summary += f", +{len(patches)-3} more"

                download_url = f"https://github.com/krishna3163/best-root-apps-for-android/releases/tag/{tag}"
                bundle_url = f"https://github.com/{item.get('bundle_repo', '')}"

                card_tags = f"morphe {build_type} {channel} autobuild autogenerated release {slug} {pkg}"

                cards.append(
                    f'<article class="app morphe-card" data-category="⚡ Morphe Patched Apps" data-tags="{html.escape(card_tags)}">'
                    f'<h2><a href="{html.escape(download_url)}">{html.escape(name)}</a></h2>'
                    f'<div class="badges">'
                    f'<span class="badge badge-{html.escape(build_type)}">[{html.escape(build_type.upper())}]</span> '
                    f'<span class="badge badge-{html.escape(channel)}">[{html.escape(channel.upper())}]</span> '
                    f'<span class="badge badge-version">v{html.escape(version)}</span>'
                    f'</div>'
                    f'<p><strong>Package:</strong> <code>{html.escape(pkg)}</code><br>'
                    f'<strong>Key Patches:</strong> {html.escape(patch_summary)}<br>'
                    f'<strong>SHA-256:</strong> <code>{html.escape(sha)}…</code></p>'
                    f'<small>⚡ Morphe Patched Apps · <a href="{html.escape(bundle_url)}" target="_blank">Bundle Source</a></small>'
                    f'<a class="source download-btn" href="{html.escape(download_url)}">⬇️ Download APK</a>'
                    "</article>"
                )
        except Exception as e:
            print(f"Error reading Morphe releases: {e}")

    OUTPUT.mkdir(exist_ok=True)
    (OUTPUT / "index.html").write_text(
        """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Best Root Apps & Morphe Patched APKs for Android</title><style>
:root{font-family:system-ui,-apple-system,sans-serif;color:#17202a;background:#f4f7f5}body{max-width:1180px;margin:auto;padding:32px 20px}header{padding:28px 0;border-bottom:1px solid #cbd5d1}h1{margin:0 0 8px;font-size:clamp(2rem,5vw,3.5rem)}header p{max-width:760px;color:#53635d;font-size:1.05rem;line-height:1.6}.controls{display:flex;gap:12px;margin:24px 0;flex-wrap:wrap}input,select{padding:12px 14px;border:1px solid #aebcb5;border-radius:8px;background:white;font:inherit}input{min-width:min(440px,100%);flex:1}.filter-chips{display:flex;gap:8px;margin-bottom:18px;flex-wrap:wrap}.chip{border:1px solid #cbd5d1;background:#fff;padding:6px 14px;border-radius:20px;font-size:0.85rem;cursor:pointer;font-weight:600;color:#2c3e50;transition:all 0.15s ease}.chip:hover,.chip.active{background:#176b4d;color:#fff;border-color:#176b4d}.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(280px,1fr));gap:14px}.app{background:white;border:1px solid #d5dfda;border-radius:8px;padding:18px;display:flex;flex-direction:column;gap:10px;box-shadow:0 2px 8px #1b33200d}.app h2{font-size:1.1rem;margin:0}.app a{color:#176b4d;text-decoration:none}.app p{margin:0;line-height:1.5;color:#42514a;font-size:0.92rem}.app small{color:#65736d}.badges{display:flex;gap:6px;flex-wrap:wrap}.badge{font-size:0.75rem;padding:2px 8px;border-radius:4px;font-weight:700}.badge-autobuild{background:#e0f2fe;color:#0369a1}.badge-autogenerated{background:#fef3c7;color:#b45309}.badge-release{background:#dcfce7;color:#15803d}.badge-beta{background:#f3e8ff;color:#7e22ce}.badge-prerelease{background:#ffe4e6;color:#be123c}.badge-version{background:#f1f5f9;color:#475569}.morphe-card{border-left:4px solid #10b981}.source{margin-top:auto;font-weight:600;text-decoration:none}.download-btn{display:inline-block;padding:8px 12px;background:#176b4d;color:white!important;border-radius:6px;text-align:center;margin-top:10px}.count{color:#65736d;margin-bottom:14px;font-weight:500}@media(max-width:600px){body{padding:20px 14px}}
</style></head><body><header><div><h1>Best Root Apps for Android 🛡️</h1><p>Search 500+ root apps, modules, system utilities, and <strong>⚡ Morphe AutoBuild & AutoGenerated Patched APKs</strong> (ad-free, sponsor-blocked, enhanced).</p><div style="display:flex;gap:10px;margin-top:12px;"><a href="morphe.html" class="chip" style="background:#176b4d;color:white;text-decoration:none;display:inline-flex;align-items:center;gap:6px;">⚡ Morphe Hub (37+ APKs)</a><a href="https://krishna3163.github.io/OpenDiscover/#/morphe" target="_blank" class="chip" style="text-decoration:none;">OpenDiscover ↗</a></div></div></header>
<main><div class="controls"><input id="search" type="search" placeholder="🔍 Search apps, autobuild, autogenerated, release, beta, packages..."><select id="category"><option value="">All categories</option></select></div><div class="filter-chips"><button class="chip active" data-filter="">All</button><button class="chip" data-filter="morphe">⚡ All Morphe APKs</button><button class="chip" data-filter="autobuild">🚀 AutoBuild</button><button class="chip" data-filter="autogenerated">⚡ AutoGenerated</button><button class="chip" data-filter="release">📦 Release</button><button class="chip" data-filter="beta">🧪 Beta</button><button class="chip" data-filter="prerelease">🚧 PreRelease</button></div><div class="count" id="count"></div><section class="grid" id="apps">"""
        + "\n".join(cards)
        + """</section></main><script>
const cards=[...document.querySelectorAll('.app')],search=document.querySelector('#search'),category=document.querySelector('#category'),count=document.querySelector('#count'),chips=[...document.querySelectorAll('.chip')];
let activeFilter='';
[...new Set(cards.map(c=>c.dataset.category))].sort().forEach(x=>category.add(new Option(x,x)));
function filter(){
  let q=search.value.toLowerCase(),c=category.value,n=0;
  cards.forEach(x=>{
    let text=x.textContent.toLowerCase();
    let tags=(x.dataset.tags||'').toLowerCase();
    let catMatch=!c||x.dataset.category===c;
    let textMatch=!q||text.includes(q)||tags.includes(q);
    let chipMatch=!activeFilter||tags.includes(activeFilter);
    let ok=catMatch&&textMatch&&chipMatch;
    x.hidden=!ok;
    if(ok)n++;
  });
  count.textContent=`${n} apps shown`;
}
search.oninput=filter;category.onchange=filter;
chips.forEach(b=>b.addEventListener('click',()=>{chips.forEach(c=>c.classList.remove('active'));b.classList.add('active');activeFilter=b.dataset.filter;filter();}));
filter();</script></body></html>""",
        encoding="utf-8",
    )
    print(f"Built {len(entries) + morphe_count} app cards ({morphe_count} Morphe cards) in {OUTPUT / 'index.html'}")

    try:
        from morphe_sync import update_all_morphe_pages
        morphe_releases_path = ROOT / "data" / "morphe-releases.json"
        morphe_status_path = ROOT / "data" / "morphe-status.json"
        morphe_config_path = ROOT / "config" / "morphe_apps.json"
        if morphe_releases_path.exists() and morphe_config_path.exists():
            with open(morphe_releases_path, "r", encoding="utf-8") as f:
                r_db = json.load(f)
            s_db = {}
            if morphe_status_path.exists():
                with open(morphe_status_path, "r", encoding="utf-8") as f:
                    s_db = json.load(f)
            with open(morphe_config_path, "r", encoding="utf-8") as f:
                c_apps = json.load(f).get("apps", [])
            update_all_morphe_pages(r_db, s_db, c_apps)
            print("Generated site/morphe.html and docs/MORPHE.md")
    except Exception as exc:
        print(f"Notice: morphe page generation: {exc}")


if __name__ == "__main__":
    build()